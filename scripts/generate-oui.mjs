// Regenerates internal/oui/registry.tsv from the IEEE Registration Authority
// MA-L, MA-M and MA-S public listings. Run it by hand and review the diff in a
// pull request; NERVE never downloads the registry at runtime.
//
//   node scripts/generate-oui.mjs            download the current listings
//   node scripts/generate-oui.mjs <dir>      use oui.csv, mam.csv and oui36.csv from <dir>
import fs from 'node:fs';
import path from 'node:path';

const registries = [
  { name: 'MA-L', file: 'oui.csv', url: 'https://standards-oui.ieee.org/oui/oui.csv', digits: 6 },
  { name: 'MA-M', file: 'mam.csv', url: 'https://standards-oui.ieee.org/oui28/mam.csv', digits: 7 },
  { name: 'MA-S', file: 'oui36.csv', url: 'https://standards-oui.ieee.org/oui36/oui36.csv', digits: 9 },
];
// Blocks the IEEE subdivides or keeps confidential carry no usable vendor;
// dropping them lets a lookup fall through instead of naming the registry.
const withheld = new Set(['ieee registration authority', 'private']);
const output = 'internal/oui/registry.tsv';

function parseCSV(text) {
  const rows = [];
  let row = [], field = '', quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(field); rows.push(row); row = []; field = '';
    } else field += c;
  }
  if (field !== '' || row.length) { row.push(field); rows.push(row); }
  return rows;
}

async function load(registry, dir) {
  if (dir) return fs.readFileSync(path.join(dir, registry.file), 'utf8');
  const response = await fetch(registry.url);
  if (!response.ok) throw Error(`${registry.url}: HTTP ${response.status}`);
  return response.text();
}

const dir = process.argv[2];
const entries = new Map();
const counts = {};
for (const registry of registries) {
  const rows = parseCSV(await load(registry, dir));
  const header = rows.shift();
  if (header?.[0] !== 'Registry' || header[1] !== 'Assignment') throw Error(`${registry.file}: unexpected header ${header}`);
  counts[registry.name] = 0;
  for (const [kind, assignment, organization] of rows) {
    if (!kind) continue;
    const prefix = (assignment ?? '').trim().toUpperCase();
    const vendor = (organization ?? '').replace(/[\s\u0000-\u001f]+/g, ' ').trim();
    if (kind !== registry.name || !new RegExp(`^[0-9A-F]{${registry.digits}}$`).test(prefix)) throw Error(`${registry.file}: bad row ${kind},${assignment}`);
    if (!vendor || withheld.has(vendor.toLowerCase()) || entries.has(prefix)) continue;
    entries.set(prefix, vendor);
    counts[registry.name]++;
  }
}
if (Object.values(counts).some((n) => n < 1000)) throw Error(`Implausibly small registry: ${JSON.stringify(counts)}`);

const lines = [...entries].sort(([a], [b]) => a.localeCompare(b)).map(([prefix, vendor]) => `${prefix}\t${vendor}`);
const summary = registries.map((r) => `${r.name} ${counts[r.name]}`).join(', ');
fs.writeFileSync(output, [
  '# IEEE Registration Authority public listings (MA-L, MA-M, MA-S), generated by scripts/generate-oui.mjs.',
  `# Retrieved ${new Date().toISOString().slice(0, 10)}: ${summary}. Format: hex prefix (6, 7 or 9 digits) TAB organization.`,
  ...lines, '',
].join('\n'));
console.log(`Wrote ${lines.length} prefixes (${summary}) to ${output}.`);
